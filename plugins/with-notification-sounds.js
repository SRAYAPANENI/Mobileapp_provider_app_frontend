const { withDangerousMod, withXcodeProject } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

// Source: an asset that already ships with the app (assets/sounds/ringtone.wav),
// previously only ever played in-app via expo-av — this plugin is what makes it
// usable as a REAL native notification-channel/APNs sound.
const SOUND_SOURCE = 'assets/sounds/ringtone.wav';
// Android raw resource names must be lowercase snake_case with no dots except
// the file extension; referenced in code (Notifee's `sound` channel field)
// WITHOUT the extension, e.g. 'direct_request_ringtone'.
const ANDROID_RAW_FILENAME = 'direct_request_ringtone.wav';
// iOS just needs the filename (with extension) bundled at the app's resource
// root; Notifee's `ios.sound` field references it exactly as this string.
const IOS_SOUND_FILENAME = 'ringtone.wav';

// Same story for the direct-request notification's Accept/Reject action
// icons: Notifee's AndroidAction.icon is typed as a plain string (a resource
// name), NOT the require()'d number largeIcon accepts — so these can't just
// be require()'d in JS either, they need to land in res/drawable/ too.
const ANDROID_ICON_SOURCES = {
  'ic_action_accept.png': 'assets/icons/action-accept.png',
  'ic_action_reject.png': 'assets/icons/action-reject.png',
};

/**
 * Copies assets/sounds/ringtone.wav (and the action icon PNGs) into both
 * native projects at prebuild time. This can't be a one-off manual file
 * copy: android/ and ios/ are gitignored and regenerated by `expo prebuild`
 * (and by every EAS build from source), so anything dropped in by hand is
 * silently wiped on the next build — the copy has to happen as a config
 * plugin mod instead.
 */
function withAndroidNotificationSound(config) {
  return withDangerousMod(config, [
    'android',
    async (config) => {
      const rawDir = path.join(config.modRequest.platformProjectRoot, 'app/src/main/res/raw');
      fs.mkdirSync(rawDir, { recursive: true });
      fs.copyFileSync(
        path.join(config.modRequest.projectRoot, SOUND_SOURCE),
        path.join(rawDir, ANDROID_RAW_FILENAME),
      );

      const drawableDir = path.join(config.modRequest.platformProjectRoot, 'app/src/main/res/drawable');
      fs.mkdirSync(drawableDir, { recursive: true });
      for (const [destName, sourceRelPath] of Object.entries(ANDROID_ICON_SOURCES)) {
        fs.copyFileSync(
          path.join(config.modRequest.projectRoot, sourceRelPath),
          path.join(drawableDir, destName),
        );
      }
      return config;
    },
  ]);
}

function withIosNotificationSound(config) {
  config = withDangerousMod(config, [
    'ios',
    async (config) => {
      const dest = path.join(
        config.modRequest.platformProjectRoot,
        config.modRequest.projectName,
        IOS_SOUND_FILENAME,
      );
      fs.copyFileSync(path.join(config.modRequest.projectRoot, SOUND_SOURCE), dest);
      return config;
    },
  ]);
  // The physical copy above isn't enough on its own — Xcode only bundles
  // files that are registered in the project as a resource, so it also has
  // to be added to the main target's "Copy Bundle Resources" build phase.
  return withXcodeProject(config, (config) => {
    const project = config.modResults;
    const groupKey = project.findPBXGroupKey({ name: config.modRequest.projectName });
    if (groupKey && !project.hasFile(IOS_SOUND_FILENAME)) {
      project.addResourceFile(IOS_SOUND_FILENAME, {}, groupKey);
    }
    return config;
  });
}

module.exports = function withNotificationSounds(config) {
  config = withAndroidNotificationSound(config);
  config = withIosNotificationSound(config);
  return config;
};
